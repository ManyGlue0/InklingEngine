"""Generate the IQ-format codebook tables for InklingEngine from llama.cpp's ggml-common.h.

usage: python tools/gen_codec_tables.py path/to/ggml/src/ggml-common.h
Writes crates/inkling-cuda/kernels/codec_tables.cuh and crates/inkling-engine/src/codec_tables.rs. The tables are
data from ggml (MIT License, Copyright (c) 2023-2026 The ggml authors; see NOTICE); they define the GGUF IQ formats.
"""
import os
import re
import sys

NAMES = ["ksigns_iq2xs", "iq2xxs_grid", "iq2xs_grid", "iq2s_grid", "iq3xxs_grid", "iq3s_grid", "iq1s_grid",
         "kvalues_iq4nl", "kvalues_fp4"]
RUST_TY = {"uint8_t": "u8", "int8_t": "i8", "uint32_t": "u32", "uint64_t": "u64"}
HEADER = ("Codebook tables of the GGUF IQ quantization formats, generated by tools/gen_codec_tables.py from ggml's\n"
          "ggml-common.h (ggml, MIT License, Copyright (c) 2023-2026 The ggml authors; see NOTICE). Do not edit.")

src = open(sys.argv[1], encoding="utf-8").read()
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tables = []
for name in NAMES:
    m = re.search(r"GGML_TABLE_BEGIN\((\w+),\s*" + name + r",\s*(\w+)\)(.*?)GGML_TABLE_END\(\)", src, re.S)
    if not m:
        sys.exit(f"table {name} not found")
    ty, body = m.group(1), m.group(3)
    vals = [v for v in re.split(r"[,\s]+", body.strip()) if v]
    size = int(m.group(2)) if m.group(2).isdigit() else len(vals)
    assert len(vals) == size, (name, len(vals), size)
    tables.append((name, ty, vals))
    print(f"{name}: {ty}[{size}]")


def rows(vals, per):
    return [", ".join(vals[i:i + per]) for i in range(0, len(vals), per)]


cu = ["#pragma once", "// " + HEADER.replace("\n", "\n// "), "namespace cdc {"]
for name, ty, vals in tables:
    per = 4 if ty.endswith("64_t") else 8 if ty.endswith("32_t") else 16
    cu.append(f"__device__ const {ty} {name}[{len(vals)}] = {{")
    cu += ["    " + r + "," for r in rows(vals, per)]
    cu.append("};")
cu.append("}  // namespace cdc\n")
open(os.path.join(root, "crates", "inkling-cuda", "kernels", "codec_tables.cuh"), "w", newline="\n").write("\n".join(cu))

rs = ["//! " + HEADER.replace("\n", "\n//! "), "", "#![allow(clippy::unreadable_literal)]"]
for name, ty, vals in tables:
    per = 4 if ty.endswith("64_t") else 8 if ty.endswith("32_t") else 16
    t = RUST_TY[ty]
    fix = [v if t != "u8" else v for v in vals]
    rs.append(f"pub static {name.upper()}: [{t}; {len(vals)}] = [")
    rs += ["    " + r + "," for r in rows(fix, per)]
    rs.append("];")
open(os.path.join(root, "crates", "inkling-engine", "src", "codec_tables.rs"), "w", newline="\n").write("\n".join(rs) + "\n")
print("wrote codec_tables.cuh and codec_tables.rs")
